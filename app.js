const grid = document.getElementById('perfumeGrid');
const searchInput = document.getElementById('perfumeSearch');
const modal = document.getElementById('modal');
const modalDetails = document.getElementById('modalDetails');
const closeBtn = document.querySelector('.close-btn');

let itemsToShow = 24;
const increment = 24;

function renderGrid(perfumes, limit) {
    if(!grid) return;
    grid.innerHTML = '';
    const slice = perfumes.slice(0, limit);
    slice.forEach(p => {
        const card = document.createElement('div');
        card.className = 'card';
        card.innerHTML = '<div class="house">' + p.brand + '</div>' +
            '<h3>' + p.name + '</h3>' +
            '<div class="accord-container">' +
                p.accords.slice(0, 3).map(a => 
                    '<div class="accord-row">' +
                        '<span class="accord-label">' + a.name + '</span>' +
                        '<div class="accord-bar-bg">' +
                            '<div class="accord-bar-fill" style="width: ' + a.val + '%"></div>' +
                        '</div>' +
                    '</div>'
                ).join('') +
            '</div>';
        card.onclick = () => openModal(p);
        grid.appendChild(card);
    });
    
    if (limit < perfumes.length) {
        const loadMore = document.createElement('div');
        loadMore.className = 'load-more-container';
        loadMore.style.gridColumn = '1 / -1';
        loadMore.style.textAlign = 'center';
        loadMore.style.padding = '40px';
        loadMore.innerHTML = '<button id="btnLoadMore" style="background: transparent; border: 1px solid #c5a059; color: #c5a059; padding: 12px 30px; cursor: pointer; font-family: Cinzel, serif; letter-spacing: 2px;">LOAD MORE</button>';
        grid.appendChild(loadMore);
        document.getElementById('btnLoadMore').onclick = () => {
            itemsToShow += increment;
            renderGrid(perfumes, itemsToShow);
        };
    }
}

function openModal(p) {
    if(!modalDetails || !modal) return;
    modalDetails.innerHTML = 
        '<div class="brand-meta">' + p.brand + ' &bull; ' + p.year + '</div>' +
        '<h2>' + p.name + '</h2>' +
        '<p class="description">' + p.description + '</p>' +
        '<div class="pyramid-grid">' +
            '<div class="pyramid-tier">' +
                '<h4>TOP NOTES</h4>' +
                '<p>' + p.top + '</p>' +
            '</div>' +
            '<div class="pyramid-tier">' +
                '<h4>HEART NOTES</h4>' +
                '<p>' + p.heart + '</p>' +
            '</div>' +
            '<div class="pyramid-tier">' +
                '<h4>BASE NOTES</h4>' +
                '<p>' + p.base + '</p>' +
            '</div>' +
        '</div>';
    modal.style.display = 'flex';
    document.body.style.overflow = 'hidden';
}

function closeModal() {
    if(!modal) return;
    modal.style.display = 'none';
    document.body.style.overflow = 'auto';
}

if(searchInput) {
    searchInput.addEventListener('input', (e) => {
        const term = e.target.value.toLowerCase();
        const filtered = perfumeData.filter(p => 
            p.name.toLowerCase().includes(term) ||
            p.brand.toLowerCase().includes(term) ||
            p.top.toLowerCase().includes(term) ||
            p.heart.toLowerCase().includes(term) ||
            p.base.toLowerCase().includes(term)
        );
        itemsToShow = 24;
        renderGrid(filtered, itemsToShow);
    });
}

if (closeBtn) closeBtn.onclick = closeModal;
window.onclick = (e) => { if (e.target == modal) closeModal(); };

